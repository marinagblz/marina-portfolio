function applyLanguage(language) {

    // Comprobar que el idioma existe
    if (!translations[language]) {
        language = "en";
    }

    // Cambiar todos los textos
    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.getAttribute("data-i18n");
        const text = translations[language][key];

        if (text === undefined) return;

        /*
         * Los enlaces "View more" tienen una flecha dentro.
         * Cambiamos solamente el texto y mantenemos la flecha.
         */
        if (element.classList.contains("project-more")) {

            const arrow = element.querySelector("span");

            if (arrow) {
                element.childNodes.forEach(node => {
                    if (node.nodeType === Node.TEXT_NODE) {
                        node.textContent = "";
                    }
                });

                element.insertBefore(
                    document.createTextNode(text + " "),
                    arrow
                );
            } else {
                element.innerHTML = text;
            }

        } else {
            element.innerHTML = text;
        }
    });


    // Cambiar el atributo lang del HTML
    document.documentElement.lang = language;


    // Marcar el idioma seleccionado
    document.querySelectorAll(".language-button").forEach(button => {
        button.classList.toggle(
            "active",
            button.dataset.language === language
        );
    });


    // Cambiar el título de la pestaña
    document.title =
        language === "es"
            ? "Marina Gallego | Data & Revenue Analytics"
            : "Marina Gallego | Data & Revenue Analytics";


    // Guardar idioma elegido
    localStorage.setItem("preferredLanguage", language);
}


// Botones de idioma
document.querySelectorAll(".language-button").forEach(button => {

    button.addEventListener("click", () => {

        const language = button.dataset.language;

        applyLanguage(language);

    });

});

// Menú móvil
const mobileMenuButton = document.querySelector(".mobile-menu-button");
const navLinks = document.querySelector(".nav-links");

mobileMenuButton.addEventListener("click", () => {
    navLinks.classList.toggle("active");
    mobileMenuButton.classList.toggle("active");
});

// Cerrar el menú al seleccionar una sección
document.querySelectorAll(".nav-links a").forEach(link => {
    link.addEventListener("click", () => {
        navLinks.classList.remove("active");
        mobileMenuButton.classList.remove("active");
    });
});


// Recuperar idioma guardado
const savedLanguage = localStorage.getItem("preferredLanguage");


// Detectar idioma del navegador si no hay uno guardado
const browserLanguage =
    navigator.language && navigator.language.startsWith("es")
        ? "es"
        : "en";


const initialLanguage = savedLanguage || browserLanguage;


// Aplicar idioma inicial
applyLanguage(initialLanguage);

